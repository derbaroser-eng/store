"""Acceptance tests for the AURUM storefront (store/index.html).

Every card must carry a real, verified Stripe checkout from the signed
suite_checkout_manifest.json, a real live product page, and no invented links.
The page is generated by build_store.py and must be byte-stable.
"""
import json
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PRODUCTS = ROOT.parent
INDEX = ROOT / "index.html"
MANIFEST = PRODUCTS / "suite_checkout_manifest.json"
SUITE = PRODUCTS / "index.html"
BASE = "https://derbaroser-eng.github.io/"
STRIPE_RE = re.compile(r"https://buy\.stripe\.com/[A-Za-z0-9_-]+")


def html():
    return INDEX.read_text(encoding="utf-8")


def manifest():
    return json.loads(MANIFEST.read_text(encoding="utf-8"))["products"]


def cards():
    out = []
    for chunk in html().split('<article class="card"')[1:]:
        slug = re.search(r'data-slug="([^"]+)"', chunk)
        links = STRIPE_RE.findall(chunk)
        page = re.search(r'class="details" href="([^"]+)"', chunk)
        out.append((slug.group(1) if slug else None, links,
                    page.group(1) if page else None))
    return out


class StoreTests(unittest.TestCase):
    def test_01_grid_count_matches_manifest(self):
        m = re.search(r'<div class="grid" data-products="(\d+)"', html())
        self.assertIsNotNone(m, "grid is missing data-products")
        self.assertEqual(int(m.group(1)), len(manifest()))

    def test_02_one_card_per_product(self):
        found = [c[0] for c in cards()]
        self.assertEqual(len(found), len(manifest()))
        self.assertEqual(set(found), set(manifest()))
        self.assertEqual(len(found), len(set(found)), "duplicate cards")

    def test_03_every_card_has_a_verified_checkout(self):
        verified = set()
        for entry in manifest().values():
            self.assertEqual(entry["http_status"], 200)
            verified |= set(entry["checkout_urls"])
        for slug, links, _ in cards():
            with self.subTest(slug=slug):
                self.assertTrue(links)
                self.assertTrue(set(links) <= verified, "unverified checkout")

    def test_04_no_invented_checkout_links(self):
        verified = set()
        for entry in manifest().values():
            verified |= set(entry["checkout_urls"])
        for link in STRIPE_RE.findall(html()):
            with self.subTest(link=link):
                self.assertIn(link, verified)

    def test_05_every_card_links_to_a_live_product_page(self):
        for slug, _, page in cards():
            with self.subTest(slug=slug):
                self.assertEqual(page, BASE + slug + "/")

    def test_06_all_hrefs_are_https(self):
        for href in re.findall(r'href="([^"]+)"', html()):
            with self.subTest(href=href):
                self.assertTrue(href.startswith("https://"), href)

    def test_07_no_placeholder_content(self):
        for token in ("TODO", "lorem", "PLACEHOLDER"):
            self.assertNotIn(token, html())
        self.assertNotRegex(html(), r'<div class="grid"[^>]*>\s*</div>')

    def test_08_generator_is_byte_stable(self):
        before = INDEX.read_bytes()
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "index.html"
            subprocess.run([sys.executable, str(ROOT / "build_store.py"),
                            "--out", str(target)], check=True, capture_output=True)
            self.assertEqual(target.read_bytes(), before)

    def test_09_suite_and_store_agree_on_product_set(self):
        suite_slugs = set(re.findall(r'<a class="card" href="' + re.escape(BASE)
                                     + r'([^/"]+)/"', SUITE.read_text(encoding="utf-8")))
        self.assertEqual(suite_slugs, set(manifest()))


if __name__ == "__main__":
    unittest.main(verbosity=2)
